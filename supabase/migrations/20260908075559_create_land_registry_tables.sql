/*
# Create LandChain registry tables

1. New Tables
- `land_registry_lands` stores the public land parcel record, including location, dimensions, survey identifier, IPFS document hash, market value, current owner wallet, sale status, and registration time.
- `land_registry_transfers` stores the append-only ownership history for each parcel, including previous owner, new owner, timestamp, and transfer note.

2. Relationships and Indexes
- Each transfer references its land parcel through `land_id`.
- Indexes support quick lookup by survey number, current owner, and transfer history.

3. Security
- Row level security is enabled on both tables.
- This application intentionally has no sign-in screen; records are public blockchain-registry data, so anon and authenticated clients may read and write the shared registry through four explicit CRUD policies per table.

4. Important Notes
- This schema backs the local demonstration flow with durable shared storage; the Solidity contract remains the on-chain source template.
- No existing tables or columns are modified or removed.
*/

CREATE TABLE IF NOT EXISTS public.land_registry_lands (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location text NOT NULL,
  area_square_meters numeric NOT NULL CHECK (area_square_meters > 0),
  survey_number text NOT NULL UNIQUE,
  document_ipfs_hash text NOT NULL,
  market_value numeric NOT NULL CHECK (market_value >= 0),
  current_owner text NOT NULL,
  is_for_sale boolean NOT NULL DEFAULT false,
  registered_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.land_registry_transfers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  land_id bigint NOT NULL REFERENCES public.land_registry_lands(id) ON DELETE CASCADE,
  from_owner text NOT NULL,
  to_owner text NOT NULL,
  transferred_at timestamptz NOT NULL DEFAULT now(),
  note text NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS land_registry_lands_owner_idx ON public.land_registry_lands(current_owner);
CREATE INDEX IF NOT EXISTS land_registry_transfers_land_idx ON public.land_registry_transfers(land_id, transferred_at);

ALTER TABLE public.land_registry_lands ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.land_registry_transfers ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "public_read_land_registry_lands" ON public.land_registry_lands;
CREATE POLICY "public_read_land_registry_lands" ON public.land_registry_lands FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "public_insert_land_registry_lands" ON public.land_registry_lands;
CREATE POLICY "public_insert_land_registry_lands" ON public.land_registry_lands FOR INSERT TO anon, authenticated WITH CHECK (true);
DROP POLICY IF EXISTS "public_update_land_registry_lands" ON public.land_registry_lands;
CREATE POLICY "public_update_land_registry_lands" ON public.land_registry_lands FOR UPDATE TO anon, authenticated USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "public_delete_land_registry_lands" ON public.land_registry_lands;
CREATE POLICY "public_delete_land_registry_lands" ON public.land_registry_lands FOR DELETE TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "public_read_land_registry_transfers" ON public.land_registry_transfers;
CREATE POLICY "public_read_land_registry_transfers" ON public.land_registry_transfers FOR SELECT TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "public_insert_land_registry_transfers" ON public.land_registry_transfers;
CREATE POLICY "public_insert_land_registry_transfers" ON public.land_registry_transfers FOR INSERT TO anon, authenticated WITH CHECK (true);
DROP POLICY IF EXISTS "public_update_land_registry_transfers" ON public.land_registry_transfers;
CREATE POLICY "public_update_land_registry_transfers" ON public.land_registry_transfers FOR UPDATE TO anon, authenticated USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "public_delete_land_registry_transfers" ON public.land_registry_transfers;
CREATE POLICY "public_delete_land_registry_transfers" ON public.land_registry_transfers FOR DELETE TO anon, authenticated USING (true);